-- ============================================================================
-- BUG1 — Identity-aware, race-safe post views
--
-- Authenticated viewers are identified by auth.uid(). Anonymous viewers are
-- identified by a server-generated opaque cookie value. The application never
-- accepts user_id or visitor_id in a browser request body/query; the anonymous
-- RPC is callable only by service_role from the trusted Next.js server route.
--
-- Each identity can count a published post once. Partial unique indexes enforce
-- that rule, while the RPC locks the post row before inserting/updating so
-- concurrent requests cannot lose increments.
-- ============================================================================

create table if not exists public.post_views (
  id uuid primary key default gen_random_uuid(),
  post_id uuid not null references public.posts (id) on delete cascade,
  user_id uuid references auth.users (id) on delete cascade,
  visitor_id text,
  viewed_at timestamptz not null default now(),
  constraint post_views_exactly_one_identity check (
    (user_id is not null and visitor_id is null)
    or (user_id is null and visitor_id is not null)
  ),
  constraint post_views_visitor_id_format check (
    visitor_id is null or visitor_id ~ '^[A-Za-z0-9_-]{43}$'
  )
);

comment on table public.post_views is
  'One counted view per post and authenticated user or server-issued anonymous visitor identity.';
comment on column public.post_views.visitor_id is
  'Opaque 32-byte base64url ID generated by the trusted server and stored in an HttpOnly cookie.';

create unique index if not exists post_views_post_user_unique_idx
  on public.post_views (post_id, user_id)
  where user_id is not null;

create unique index if not exists post_views_post_visitor_unique_idx
  on public.post_views (post_id, visitor_id)
  where visitor_id is not null;

alter table public.post_views enable row level security;

-- There is no direct client access. The narrowly scoped SECURITY DEFINER RPCs
-- below are the only permitted write path.
revoke all on table public.post_views from anon, authenticated;

-- ----------------------------------------------------------------------------
-- Non-breaking rollout note:
--
-- public.increment_post_view(uuid) (the old anon/authenticated increment) is
-- intentionally LEFT IN PLACE by this migration. The currently live Vercel
-- application still calls it, so dropping it here would break the production
-- view counter before the new route is deployed.
--
-- After this migration is live AND the new application code is deployed AND
-- real authenticated/anonymous/concurrency tests pass, remove the old RPC in a
-- separate cleanup migration:
--
--   drop function if exists public.increment_post_view(uuid);
--   revoke execute on function public.increment_post_view(uuid) from anon, authenticated;
-- ----------------------------------------------------------------------------

-- ----------------------------------------------------------------------------
-- Authenticated viewer RPC
-- ----------------------------------------------------------------------------
create or replace function public.record_authenticated_post_view(p_post_id uuid)
returns table (view_count integer, counted boolean)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_view_count integer;
  v_inserted integer;
begin
  -- Never accept an authenticated identity as an argument.
  if v_user_id is null then
    return;
  end if;

  -- Lock the published post first. This serializes view writes for the post
  -- and prevents an unpublish/update race with the count increment.
  select p.view_count
    into v_view_count
  from public.posts p
  where p.id = p_post_id
    and p.status = 'published'
  for update;

  if not found then
    return;
  end if;

  insert into public.post_views (post_id, user_id)
  values (p_post_id, v_user_id)
  on conflict do nothing;

  get diagnostics v_inserted = row_count;

  if v_inserted = 1 then
    update public.posts p
      set view_count = p.view_count + 1
    where p.id = p_post_id
    returning p.view_count into v_view_count;

    return query select v_view_count, true;
  end if;

  return query select v_view_count, false;
end;
$$;

comment on function public.record_authenticated_post_view(uuid) is
  'Counts one view for auth.uid() per published post. User identity is derived server-side.';

-- ----------------------------------------------------------------------------
-- Anonymous viewer RPC
-- ----------------------------------------------------------------------------
create or replace function public.record_anonymous_post_view(
  p_post_id uuid,
  p_visitor_id text
)
returns table (view_count integer, counted boolean)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_view_count integer;
  v_inserted integer;
begin
  -- This function is granted only to service_role. Validate the server-issued
  -- cookie shape again at the database boundary as defense in depth.
  if p_visitor_id is null
     or p_visitor_id !~ '^[A-Za-z0-9_-]{43}$' then
    return;
  end if;

  select p.view_count
    into v_view_count
  from public.posts p
  where p.id = p_post_id
    and p.status = 'published'
  for update;

  if not found then
    return;
  end if;

  insert into public.post_views (post_id, visitor_id)
  values (p_post_id, p_visitor_id)
  on conflict do nothing;

  get diagnostics v_inserted = row_count;

  if v_inserted = 1 then
    update public.posts p
      set view_count = p.view_count + 1
    where p.id = p_post_id
    returning p.view_count into v_view_count;

    return query select v_view_count, true;
  end if;

  return query select v_view_count, false;
end;
$$;

comment on function public.record_anonymous_post_view(uuid, text) is
  'Counts one view per server-issued anonymous visitor ID and published post; service_role only.';

revoke execute on function public.record_authenticated_post_view(uuid) from public, anon;
grant execute on function public.record_authenticated_post_view(uuid) to authenticated;

revoke execute on function public.record_anonymous_post_view(uuid, text) from public, anon, authenticated;
grant execute on function public.record_anonymous_post_view(uuid, text) to service_role;
