export function normalizeKey(s: string): string {
  return String(s || '')
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function extractMenuItems(menuText: string): string[] {
  const items: string[] = [];
  const re = /\*(.*?)\*/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(menuText)) !== null) {
    const t = m[1]
      .replace(/^[^a-zA-Z0-9]+/, '')
      .replace(/\.+/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
    if (t) items.push(t);
  }
  return items;
}

