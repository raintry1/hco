normalized[normalizeKey('menu')] = BOLT_MENU;

export function findBestMatch(
  input: string
): { key: string; reply: string } | null {
  const inKey = normalizeKey(input);
  if (normalized[inKey]) return { key: inKey, reply: normalized[inKey] };

  const inputTokens = inKey.split(' ').filter(Boolean);
  let best: { key: string; score: number; reply: string } = {
    key: '',
    score: 0,
    reply: '',
  };
  for (const k of Object.keys(normalized)) {
    const kTokens = k.split(' ').filter(Boolean);
    const setK = new Set(kTokens);
    const inter = inputTokens.filter((t) => setK.has(t)).length;
    const score = inputTokens.length ? inter / inputTokens.length : 0;
    if (score > best.score) best = { key: k, score, reply: normalized[k] };
  }
  return best.score >= 0.5 ? { key: best.key, reply: best.reply } : null;
}

export function getBoltReply(input: string): string {
  if (normalizeKey(input) === 'menu') return BOLT_MENU;
  const match = findBestMatch(input);
  return match ? match.reply : "Command not found. Type 'menu' to see options.";
}

